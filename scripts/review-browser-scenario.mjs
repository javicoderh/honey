import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";

export async function runReviewScenario({ evaluate, waitFor, click, navigate, send }) {
  await send('Emulation.setFocusEmulationEnabled', { enabled: true });
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  assert.equal(await evaluate("getComputedStyle(document.documentElement).scrollBehavior"), 'auto');
  const fill = (selector, value) => evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, ${JSON.stringify(value)}); el.dispatchEvent(new Event('input', { bubbles: true })); })()`);
  const key = async (key, code = key, modifiers = 0) => {
    const windowsVirtualKeyCode = { Enter: 13, Tab: 9, Escape: 27 }[key];
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key, code, modifiers, windowsVirtualKeyCode, ...(key === 'Enter' ? { text: '\r' } : {}) });
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key, code, modifiers, windowsVirtualKeyCode });
  };
  const capture = async (name, width) => {
    await send('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: width < 600 });
    await waitFor('document.fonts.status === "loaded"');
    assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, `${name}: desbordamiento a ${width}px`);
    const unnamed = await evaluate(`([...document.querySelectorAll('main input:not([type=hidden]), main select, main textarea')].filter(el => !el.labels?.length && !el.getAttribute('aria-label') && !el.getAttribute('aria-labelledby'))).map(el => el.outerHTML)`);
    assert.deepEqual(unnamed, [], `${name}: campos sin nombre accesible`);
    const modal = await evaluate("!!document.querySelector('dialog[open]')");
    await writeFile(`.preview-browser/review-${name}-${width}.png`, Buffer.from((await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: !modal })).data, 'base64'));
  };
  await evaluate(`(async () => {
    const { services } = await import('/src/services/index.js');
    const { createMockAdapter } = await import('/src/services/mock.js');
    const { createReviewOrders } = await import('/scripts/fixtures/review-orders.mjs');
    const adapter = createMockAdapter({ initialOrders: createReviewOrders() });
    await adapter.auth.login({ email: 'admin@casamiel.demo', password: 'demo1234' });
    Object.assign(services, adapter); window.reviewApi = services;
  })()`);
  await navigate('/staff/admin/pedidos');
  await click('Actualizar pedidos');
  await click('Todos');
  await waitFor("document.querySelectorAll('.order-list > li').length === 7");
  await waitFor("document.activeElement.id === 'contenido'");
  await capture('orders', 1280);
  await capture('orders', 390);
  await navigate('/staff/admin');
  await waitFor("document.body.innerText.includes('2 integrantes activos')");
  await capture('admin', 1280);
  await capture('admin', 390);
  await navigate('/staff/admin/despachos');
  await waitFor("document.body.innerText.includes('Por preparar (1)')");
  for (const label of ['Listos para despacho (1)', 'En reparto (1)', 'Entrega no realizada (1)', 'Entregados (1)']) {
    await click(label);
    await waitFor("document.querySelectorAll('.delivery-record').length === 1");
  }
  await capture('dispatch', 390);
  await navigate('/staff/admin/equipo');
  await waitFor("document.querySelectorAll('.team-member').length === 2");
  // La consulta diferida permite observar carga, error y recuperación reales del contexto.
  await evaluate("window.originalTeamList = window.reviewApi.staff.list; window.reviewApi.staff.list = () => new Promise((resolve, reject) => { window.rejectTeamList = reject; })");
  await click('Actualizar equipo');
  await waitFor("document.body.innerText.includes('Cargando equipo')");
  await evaluate("window.rejectTeamList(new Error('Fallo de revisión'))");
  await waitFor("document.body.innerText.includes('No pudimos consultar el equipo')");
  await evaluate("window.reviewApi.staff.list = window.originalTeamList");
  await click('Actualizar equipo');
  await waitFor("document.querySelectorAll('.team-member').length === 2");
  await click('Crear integrante');
  await click('Revisar nueva cuenta');
  await waitFor("document.activeElement.getAttribute('aria-invalid') === 'true'");
  await capture('team-form', 1280);
  await capture('team-form', 390);
  // Abrir con teclado, mantener foco en el modal y cerrarlo con Escape.
  await evaluate("document.querySelector('[data-member-id=demo-delivery] button:last-child').focus()");
  assert.equal(await evaluate("document.activeElement.textContent.trim()"), 'Desactivar acceso');
  await key('Enter');
  await waitFor("!!document.querySelector('dialog[open]')");
  assert.equal(await evaluate("!!document.activeElement.closest('dialog')"), true);
  await key('Tab', 'Tab', 8);
  await key('Tab');
  assert.equal(await evaluate("!!document.activeElement.closest('dialog')"), true);
  assert.equal(await evaluate("getComputedStyle(document.activeElement).outlineStyle !== 'none'"), true);
  await capture('confirmation', 390);
  await key('Escape');
  await waitFor("!document.querySelector('dialog[open]')");
  assert.equal(await evaluate("document.activeElement.textContent.trim()"), 'Desactivar acceso');
  await click('Cerrar sesión');
  await waitFor("document.body.innerText.includes('Cuentas de demostración')");
  await capture('login', 1280);
  await capture('login', 390);
  await fill('input[type=email]', 'nobody@example.com');
  await fill('input[type=password]', 'review-only-do-not-store');
  await click('Iniciar sesión');
  await waitFor("document.body.innerText.includes('incorrectos')");
  assert.equal(await evaluate("[JSON.stringify(localStorage), JSON.stringify(sessionStorage)].some(value => /review-only-do-not-store|nobody@example.com|demo1234/.test(value))"), false);
  await click('Usar cuenta delivery');
  await click('Iniciar sesión');
  await waitFor("document.body.innerText.includes('Pendientes de entrega (3)')");
  await click('Pendientes de entrega (3)');
  await capture('delivery', 1280);
  await capture('delivery', 390);
  await click('Historial de entregas (1)');
  await waitFor("document.querySelectorAll('.delivery-record').length === 1");
  await click('Cerrar sesión');
  await navigate('/productos/miel-multifloral');
  await waitFor("[...document.querySelectorAll('button')].some(el => el.textContent.trim() === 'Agregar al carrito' && !el.disabled)");
  await click('Agregar al carrito');
  await navigate('/checkout');
  await waitFor("!!document.querySelector('form[aria-label=\"Datos de compra\"]')");
  await click('Continuar al pago simulado');
  await waitFor("document.activeElement.getAttribute('aria-invalid') === 'true'");
  await capture('checkout', 1280);
  await capture('checkout', 390);
  await capture('checkout', 360);
  assert.equal(await evaluate("document.body.innerText.includes('No se realizará ningún cobro real.') && document.body.innerText.includes('Despacho simulado')"), true);
  await navigate('/checkout/resultado');
  await waitFor("document.body.innerText.includes('No hay un pedido para consultar')");
  await navigate('/checkout');
  await waitFor("!!document.querySelector('form[aria-label=\"Datos de compra\"]')");
  assert.deepEqual(await evaluate("[...document.querySelectorAll('form input[required]')].map(el => el.name)"), ['buyer.name', 'buyer.email', 'buyer.phone', 'shippingAddress.street', 'shippingAddress.commune']);
  assert.equal(await evaluate("!!document.querySelector('input[name=\"shippingAddress.apartment\"]').required || !!document.querySelector('input[name=\"shippingAddress.reference\"]').required || !!document.querySelector('form textarea').required"), false);
  await evaluate("document.querySelector('.checkout-checkbox input').click()");
  await click('Continuar al pago simulado');
  await waitFor("document.querySelector('input[name=\"recipient.name\"]').getAttribute('aria-invalid') === 'true'");
  assert.equal(await evaluate("document.querySelector('input[name=\"recipient.phone\"]').required"), true);
  await evaluate("document.querySelector('.checkout-checkbox input').click()");
  await fill('input[name="buyer.name"]', "María-José O'Ryan");
  await fill('input[name="buyer.email"]', 'maria..pedido@example.cl');
  await fill('input[name="buyer.phone"]', '--------');
  await fill('input[name="shippingAddress.street"]', 'Camino rural s/n');
  await fill('input[name="shippingAddress.commune"]', 'Pucón');
  await click('Continuar al pago simulado');
  await waitFor("document.querySelector('input[name=\"buyer.email\"]').getAttribute('aria-invalid') === 'true'");
  assert.equal(await evaluate("document.querySelector('input[name=\"buyer.phone\"]').getAttribute('aria-invalid')"), 'true');
  const before = await evaluate('(async () => (await window.reviewApi.orders.list()).length)()');
  await fill('input[name="buyer.email"]', 'maria+pedido@example.cl');
  await fill('input[name="buyer.phone"]', '+56 (9) 1234-5678');
  await waitFor("!document.querySelector('form [aria-invalid=true]')");
  await evaluate("window.originalCreate = window.reviewApi.orders.create; window.reviewApi.orders.create = async () => { throw Error('No pudimos guardar el pedido de prueba'); }");
  await click('Continuar al pago simulado');
  await waitFor("document.body.innerText.includes('No pudimos guardar el pedido de prueba')");
  assert.equal(await evaluate("document.querySelector('input[name=\"buyer.email\"]').value"), 'maria+pedido@example.cl');
  assert.equal(await evaluate('(async () => (await window.reviewApi.orders.list()).length)()'), before);
  await evaluate('window.reviewApi.orders.create = window.originalCreate');
  await click('Continuar al pago simulado');
  await waitFor("location.pathname === '/checkout/resultado' && document.body.innerText.includes('Simulador de pago')");
  const created = await evaluate("(async () => (await window.reviewApi.orders.list()).find(order => order.buyer.email === 'maria+pedido@example.cl'))()");
  assert.equal(created.shippingAddress.apartment, '');
  assert.equal(created.shippingAddress.reference, '');
  assert.equal(created.deliveryInstructions, '');
  console.log('Revisión integral: siete escenarios, estados de consulta, dashboards y formularios a 1280/390/360px, nombres accesibles, foco tras navegación, validación, teclado/modal, credenciales sin persistencia y avisos de simulación verificados.');
}
