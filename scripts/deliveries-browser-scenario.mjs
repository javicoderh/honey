import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";

export async function runDeliveriesScenario({ evaluate, waitFor, click, navigate, send }) {
  const fill = (label, value) => evaluate(`(() => {
    const node = [...document.querySelectorAll('label')].find(el => el.textContent.trim() === ${JSON.stringify(label)});
    if (!node) throw Error('Campo no encontrado: ' + ${JSON.stringify(label)});
    const input = document.getElementById(node.htmlFor);
    Object.getOwnPropertyDescriptor(input.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(input, ${JSON.stringify(value)});
    input.dispatchEvent(new Event('input', { bubbles: true }));
  })()`);
  const confirm = async () => {
    await waitFor("!!document.querySelector('dialog[open]')");
    await evaluate("document.querySelector('dialog[open] .commerce-button--primary').click()");
  };
  const openRecord = async () => {
    await waitFor("!!document.querySelector('.delivery-record')");
    await evaluate("document.querySelector('.delivery-record').click()");
    await waitFor("document.body.innerText.includes('Estado de la entrega')");
  };
  await evaluate(`(async () => {
    const { services } = await import('/src/services/index.js');
    const { createMockAdapter } = await import('/src/services/mock.js');
    const { products } = await import('/src/data/products.js');
    const { createOrder, recordPaymentUpdate, recordDeliveryUpdate, assignOrderDelivery } = await import('/src/modules/orders/model.js');
    const at = new Date(Date.now() - 60000).toISOString();
    const admin = { id: 'demo-admin', name: 'Admin', role: 'admin' };
    const base = (id, name) => createOrder({ id, number: 'CM-' + id, createdAt: at, shippingFee: 3000, catalog: products, items: [{ slug: 'miel-multifloral', format: '1 kg', quantity: 1 }], draft: { buyer: { name: 'Comprador ajeno', email: id + '@example.com', phone: '+56911111111' }, recipientSameAsBuyer: false, recipient: { name, phone: '+56933333333' }, shippingAddress: { street: 'Otra calle 45', commune: 'Pucón' }, deliveryInstructions: 'Otra dirección privada' } });
    let other = base('OTHER', 'Destinatario ajeno');
    other = recordPaymentUpdate(other, { paymentId: other.payments[0].id, status: 'approved', transactionId: 'tx-other', at, author: { id: 'system', name: 'Pagos', role: 'system' } });
    other = recordDeliveryUpdate(other, { status: 'ready', at, author: admin });
    other = assignOrderDelivery(other, { assignee: { id: 'other-delivery', name: 'Otro reparto', role: 'delivery', active: true }, at, author: admin });
    const adapter = createMockAdapter({ initialOrders: [other, base('UNPAID', 'Pedido sin pagar')] });
    await adapter.auth.login({ email: 'admin@casamiel.demo', password: 'demo1234' });
    Object.assign(services, adapter); window.deliveryTestApi = services;
    localStorage.removeItem('casa-miel.cart.v1');
  })()`);
  await navigate("/productos/miel-multifloral");
  await waitFor("[...document.querySelectorAll('button')].some(el => el.textContent.trim() === 'Agregar al carrito' && !el.disabled)");
  await click("Agregar al carrito");
  await navigate("/carrito");
  await waitFor("document.body.innerText.includes('Continuar con mi compra')");
  await click("Continuar con mi compra ↗");
  await waitFor("!!document.querySelector('form[aria-label=\"Datos de compra\"]')");
  await fill("Nombre completo", "Comprador privado");
  await fill("Correo electrónico", "privado@example.com");
  await fill("Teléfono", "+56911111111");
  await evaluate("document.querySelector('.checkout-checkbox input').click()");
  await fill("Nombre del destinatario", "Receptora del pedido");
  await fill("Teléfono del destinatario", "+56922222222");
  await fill("Calle y número", "Calle de prueba 123");
  await fill("Comuna", "Pucón");
  await fill("Indicaciones de entrega (opcional)", "Entregar solo a la destinataria");
  await click("Continuar al pago simulado");
  await waitFor("[...document.querySelectorAll('button')].some(el => el.textContent.trim() === 'Simular pago' && !el.disabled)");
  await click("Simular pago");
  await waitFor("document.body.innerText.includes('Pago simulado aprobado')");
  const created = await evaluate("(async () => { window.createdDeliveryOrder = (await window.deliveryTestApi.orders.list()).find(order => order.buyer.email === 'privado@example.com'); return window.createdDeliveryOrder; })()");
  assert.equal(created.total, 9990);
  await navigate("/staff/admin/despachos");
  await waitFor("document.querySelectorAll('.delivery-record').length === 1");
  assert.equal(await evaluate("document.querySelector('.delivery-records').innerText.includes('Pedido sin pagar')"), false);
  await openRecord();
  await click("Marcar listo para despacho");
  await confirm();
  await waitFor("!!document.querySelector('.form-field select') && !document.querySelector('.form-field select').disabled");
  await evaluate("(() => { const el = document.querySelector('.form-field select'); el.value = 'demo-delivery'; el.dispatchEvent(new Event('change', { bubbles: true })); })()");
  await click("Revisar asignación");
  await confirm();
  await waitFor("document.body.innerText.includes('Delivery asignado') && !document.querySelector('dialog[open]')");
  await click("← Volver a despachos");
  await waitFor("document.body.innerText.includes('Listos para despacho (2)')");
  await click("Listos para despacho (2)");
  await fill("Buscar por pedido, destinatario o comuna", "Receptora");
  await openRecord();
  await click("← Volver a despachos");
  await waitFor("document.querySelector('input[type=search]')?.value === 'Receptora'");
  await click("Cerrar sesión");
  await waitFor("document.body.innerText.includes('Cuentas de demostración')");
  await click("Usar cuenta delivery");
  await click("Iniciar sesión");
  await waitFor("document.body.innerText.includes('Pendientes de entrega (1)')");
  assert.equal(await evaluate("!!document.querySelector('.delivery-section')"), false);
  await click("Pendientes de entrega (1)");
  await waitFor("document.querySelectorAll('.delivery-record').length === 1");
  assert.equal(await evaluate("document.body.innerText.includes('Destinatario ajeno')"), false);
  await openRecord();
  assert.equal(await evaluate("document.body.innerText.includes('Comprador privado') || document.body.innerText.includes('privado@example.com') || document.body.innerText.includes('$')"), false);
  assert.equal(await evaluate("document.querySelector('a[href^=tel]').getAttribute('href')"), "tel:+56922222222");
  assert.ok((await evaluate("document.querySelector('a[href^=\"https://maps.google.com\"]').getAttribute('href')")).includes("Calle%20de%20prueba%20123"));
  const scoped = await evaluate("window.deliveryTestApi.orders.listAssigned()");
  assert.equal(scoped[0].buyer, undefined);
  assert.equal(scoped[0].payments, undefined);
  assert.equal(scoped[0].items[0].unitPrice, undefined);
  await fill("Comentario", "Destinataria avisada por teléfono");
  await click("Guardar comentario");
  await waitFor("document.body.innerText.includes('Destinataria avisada por teléfono') && document.body.innerText.includes('Comentario interno agregado')");
  await click("Marcar en reparto"); await confirm();
  await waitFor("!document.querySelector('dialog[open]') && document.body.innerText.includes('En reparto')");
  await click("Entrega no realizada"); await confirm();
  await waitFor("document.body.innerText.includes('Indica un motivo para continuar.')");
  await fill("Motivo", "Destinataria ausente"); await confirm();
  await waitFor("document.body.innerText.includes('Destinataria ausente') && !document.querySelector('dialog[open]')");
  await click("Marcar en reparto"); await confirm();
  await waitFor("!document.querySelector('dialog[open]') && document.body.innerText.includes('En reparto')");
  await click("Marcar entregado"); await confirm();
  await waitFor("document.body.innerText.includes('Confirmada por') && [...document.querySelectorAll('button')].some(el => el.textContent.trim() === 'Marcar entregado' && el.disabled)");
  await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  assert.equal(await evaluate("document.documentElement.scrollWidth <= innerWidth"), true);
  await writeFile(".preview-browser/delivery-mobile.png", Buffer.from((await send("Page.captureScreenshot", { format: "png", captureBeyondViewport: true })).data, "base64"));
  await click("← Volver a mis entregas");
  await waitFor("document.body.innerText.includes('Sin entregas pendientes')");
  await click("Historial de entregas (1)");
  await openRecord();
  await click("Marcar en reparto"); await confirm();
  await waitFor("document.body.innerText.includes('Indica un motivo para continuar.')");
  await fill("Motivo", "Marcado por error"); await confirm();
  await waitFor("document.body.innerText.includes('Fecha de entrega anterior conservada:') && !document.querySelector('dialog[open]')");
  await click("Marcar entregado"); await confirm();
  await waitFor("[...document.querySelectorAll('button')].some(el => el.textContent.trim() === 'Marcar entregado' && el.disabled)");
  await navigate("/staff/delivery/OTHER");
  await waitFor("document.body.innerText.includes('Entrega no disponible')");
  assert.equal(await evaluate("document.body.innerText.includes('Destinatario ajeno') || document.body.innerText.includes('Gestionar mi entrega')"), false);
  await click("Cerrar sesión");
  await waitFor("document.body.innerText.includes('Cuentas de demostración')");
  await click("Usar cuenta admin"); await click("Iniciar sesión");
  await waitFor("location.pathname === '/staff/admin'");
  await navigate(`/staff/admin/pedidos/${created.id}`);
  await waitFor("document.body.innerText.includes('Gestión del pedido') && document.body.innerText.includes('Destinataria avisada por teléfono')");
  assert.ok(await evaluate("document.body.innerText.includes('Comprador privado')"));
  await navigate(`/staff/admin/ventas/${created.id}`);
  await waitFor("document.body.innerText.includes('Pago de la venta') && document.body.innerText.includes('Entregado')");
  const saved = await evaluate("window.deliveryTestApi.orders.getById(window.createdDeliveryOrder.id)");
  assert.equal(saved.delivery.status, "delivered");
  assert.equal(saved.delivery.deliveredBy.id, "demo-delivery");
  assert.equal(saved.comments.length, 1);
  assert.equal(saved.payments.length, 1);
  assert.equal(saved.total, 9990);
  console.log("Navegador despachos: compra invitada y pago simulado, preparación/asignación admin, ámbito delivery sin datos comerciales, contacto/mapa, comentario, reparto/entrega fallida/entrega y corrección, historial, móvil, pedido ajeno bloqueado y datos reflejados en Pedidos/Ventas verificados.");
}
